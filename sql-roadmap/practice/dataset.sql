-- Запускайте в отдельном учебном соединении. Таблицы временные.
-- Повторный запуск — в новом соединении. Рабочие таблицы не изменяются.
SET TIME ZONE 'UTC';

CREATE TEMP TABLE pa_users (
    user_id integer PRIMARY KEY,
    registered_at timestamptz NOT NULL,
    channel text
);
CREATE TEMP TABLE pa_orders (
    order_id integer PRIMARY KEY,
    user_id integer NOT NULL REFERENCES pa_users(user_id),
    paid_at timestamptz,
    amount numeric(12,2) NOT NULL,
    status text NOT NULL
);
CREATE TEMP TABLE pa_events_raw (
    ingest_id integer PRIMARY KEY,
    event_id integer NOT NULL,
    user_id integer REFERENCES pa_users(user_id),
    event_name text NOT NULL,
    event_at timestamptz NOT NULL,
    ingested_at timestamptz NOT NULL
);

